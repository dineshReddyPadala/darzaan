-- Notification and message-log ids become autoincrement integers. Event ids stay text.
ALTER TABLE "notifications" ADD COLUMN "new_id" INTEGER;
ALTER TABLE "notifications" ADD COLUMN "new_order_id" INTEGER;
UPDATE "notifications" n SET "new_id" = s.rn
FROM (
  SELECT "id", ROW_NUMBER() OVER (ORDER BY "created_at", "id")::int AS rn FROM "notifications"
) s
WHERE n."id" = s."id";
UPDATE "notifications" SET "new_order_id" = "order_id"::int WHERE "order_id" ~ '^[1-9][0-9]*$';

ALTER TABLE "message_logs" ADD COLUMN "new_id" INTEGER;
UPDATE "message_logs" m SET "new_id" = s.rn
FROM (
  SELECT "id", ROW_NUMBER() OVER (ORDER BY "created_at", "id")::int AS rn FROM "message_logs"
) s
WHERE m."id" = s."id";

ALTER TABLE "notifications" DROP CONSTRAINT "notifications_pkey";
ALTER TABLE "notifications" DROP COLUMN "id";
ALTER TABLE "notifications" DROP COLUMN "order_id";
ALTER TABLE "notifications" RENAME COLUMN "new_id" TO "id";
ALTER TABLE "notifications" RENAME COLUMN "new_order_id" TO "order_id";
ALTER TABLE "notifications" ALTER COLUMN "id" SET NOT NULL;
ALTER TABLE "notifications" ADD PRIMARY KEY ("id");
ALTER TABLE "notifications" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('notifications', 'id'), GREATEST(COALESCE((SELECT MAX("id") FROM "notifications"), 1), 1), (SELECT COUNT(*) FROM "notifications") > 0);

ALTER TABLE "message_logs" DROP CONSTRAINT "message_logs_pkey";
ALTER TABLE "message_logs" DROP COLUMN "id";
ALTER TABLE "message_logs" RENAME COLUMN "new_id" TO "id";
ALTER TABLE "message_logs" ALTER COLUMN "id" SET NOT NULL;
ALTER TABLE "message_logs" ADD PRIMARY KEY ("id");
ALTER TABLE "message_logs" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY;
