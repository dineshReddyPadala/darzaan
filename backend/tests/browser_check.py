import os,subprocess,time
from playwright.sync_api import sync_playwright
p=subprocess.Popen(['uvicorn','app:app','--host','127.0.0.1','--port','8932'],cwd='/mnt/data/darzaan_live',stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
try:
 time.sleep(2)
 with sync_playwright() as pl:
  browser=pl.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  page=browser.new_page(viewport={'width':1440,'height':900})
  errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto('http://127.0.0.1:8932/',wait_until='load')
  page.screenshot(path='/mnt/data/Darzaan_Production_Desktop_QA.png',full_page=False)
  print('title:',page.title(),'home visible:',page.locator('[data-page="home"]').get_attribute('class'))
  print('buttons:',page.locator('[data-book]').count())
  page.locator('[data-book]').first.click()
  print('modal',page.locator('#bookingModal').get_attribute('class'))
  page.locator('#nextBook').click()
  page.wait_for_timeout(500)
  print('slot_buttons',page.locator('[data-time]').count())
  page.locator('[data-time]:not([disabled])').first.click()
  page.locator('#nextBook').click()
  page.locator('#apName').fill('Kavya Tester')
  page.locator('#apPhone').fill('9876543210')
  page.locator('#apConsent').check()
  page.locator('#bookingSubmit').click()
  page.wait_for_timeout(800)
  print('success:',page.locator('.success').count(),'text:',page.locator('.success').inner_text()[:140] if page.locator('.success').count() else page.locator('#bookingError').inner_text())
  mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,device_scale_factor=1)
  mobile.goto('http://127.0.0.1:8932/',wait_until='load')
  mobile.screenshot(path='/mnt/data/Darzaan_Production_Mobile_QA.png',full_page=False)
  print('mobile overflow:',mobile.evaluate('document.documentElement.scrollWidth > innerWidth'))
  print('page errors',errors)
  browser.close()
finally:p.terminate();p.wait(timeout=10)
